/// Quick actions (docs/AI_LAYER.md → "פעולות מהירות").
#[must_use]
pub fn quick_action(key: &str) -> Option<&'static str> {
    Some(match key {
        "expand" => "הרחב/י את הטיוטה של הסעיף, רק על סמך המידע שיש. סמן/י [חסר: …] במקום להמציא.",
        "shorten" => "קצר/י את הטיוטה של הסעיף ושמור/י על כל הממצאים.",
        "analyze" => "נתח/י את הטיוטה מול הממצאים בסעיפים שאושרו: האם יש סתירות, פערים או ממצאים שלא נוצלו? החזר/י הצעות בלבד.",
        "recommend" => "הצע/י המלצות שנובעות מהממצאים המאושרים, כל אחת עם הממצא שמבסס אותה.",
        "rephrase" => "נסח/י מחדש את הפסקה האחרונה שהוצעה, בסגנון הפרופיל.",
        _ => return None,
    })
}
